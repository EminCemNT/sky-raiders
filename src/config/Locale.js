export const L = { zh, en };

// 当前语言（'zh' | 'en'）；默认 zh 保持既有中文文案零回归
let _lang = 'zh';

/** 初始化语言（启动时按存档字段调用一次；非法值回退 zh） */
export function initLocale(lang) {
  _lang = (lang === 'en') ? 'en' : 'zh';
  return _lang;
}

/** 当前语言 */
export function getLocale() {
  return _lang;
}

/** 切换语言（持久化由调用方写入 SaveManager.lang） */
export function setLocale(lang) {
  _lang = (lang === 'en') ? 'en' : 'zh';
  return _lang;
}

/**
 * 取当前语言文案；支持 {key} 模板占位符（如 t('saveInfo', {coins})）。
 * 缺失 key 回退 zh，再缺失返回 key 本身（开发期可直观定位未收录文案）。
 */
export function t(key, vars) {
  const table = L[_lang] || L.zh;
  let s = table[key];
  if (s == null) s = L.zh[key];
  if (s == null) return key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split('{' + k + '}').join(String(vars[k] == null ? '' : vars[k]));
    }
  }
  return s;
}
